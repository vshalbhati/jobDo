// The dashboard has one source of truth: frontend/public/app.
//
// The extension cannot load it over the network (Manifest V3 forbids remote
// code), so it needs its own copy on disk. This script makes that copy, and
// running it is the only supported way to change the extension's dashboard.
//
//   node scripts/sync-dashboard.mjs           copy
//   node scripts/sync-dashboard.mjs --check   fail if the copy is stale (for CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const from = path.join(root, 'frontend', 'public', 'app');
const to = path.join(root, 'extension', 'src', 'dashboard');

const COPY = ['dashboard.css', 'dashboard.js', 'charts.js', 'source.js'];
const checkOnly = process.argv.includes('--check');

const BANNER = '/* Generated by scripts/sync-dashboard.mjs from frontend/public/app. Edit the original. */\n';

// The web page pulls in ../config.js for its API base URL. The extension has no
// such file and never needs one, so that tag is dropped on the way across.
function extensionHtml(html) {
  return html
    .replace(/[ \t]*<script src="\.\.\/config\.js"><\/script>\n?/g, '')
    .replace('<title>jobDo — Dashboard</title>',
      '<title>jobDo — Dashboard</title>\n<!-- Generated by scripts/sync-dashboard.mjs. Edit frontend/public/app/index.html. -->');
}

function planned() {
  const out = new Map();
  for (const name of COPY) {
    const body = readFileSync(path.join(from, name), 'utf8');
    out.set(name, name.endsWith('.js') ? BANNER + body : body);
  }
  out.set('dashboard.html', extensionHtml(readFileSync(path.join(from, 'index.html'), 'utf8')));
  return out;
}

const files = planned();

if (checkOnly) {
  const stale = [];
  for (const [name, body] of files) {
    const target = path.join(to, name);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== body) stale.push(name);
  }
  if (stale.length) {
    console.error('Extension dashboard is out of date: ' + stale.join(', '));
    console.error('Run: node scripts/sync-dashboard.mjs');
    process.exit(1);
  }
  console.log('Extension dashboard is in sync.');
} else {
  mkdirSync(to, { recursive: true });
  for (const [name, body] of files) {
    writeFileSync(path.join(to, name), body);
    console.log('  ' + path.relative(root, path.join(to, name)));
  }
  console.log('\nCopied ' + files.size + ' files from frontend/public/app.');
}
