// Code that both the web app and the extension run has exactly one source of
// truth, and this script copies it to the other side. Neither side can load
// the other's files at runtime: Manifest V3 forbids remote code, and the web
// app deploys only frontend/public.
//
//   dashboard   frontend/public/app       ->  extension/src/dashboard
//   shared      extension/src/shared/...  ->  frontend/public/shared
//               (settings defaults, job boards, career sites, resume parsing)
//
//   node scripts/sync-dashboard.mjs           copy
//   node scripts/sync-dashboard.mjs --check   fail if a copy is stale (for CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

const banner = (from) => '/* Generated by scripts/sync-dashboard.mjs from ' + from + '. Edit the original. */\n';

// The web page pulls in ../config.js for its API base URL. The extension has no
// such file and never needs one, so that tag is dropped on the way across.
function extensionHtml(html) {
  return html
    .replace(/[ \t]*<script src="\.\.\/config\.js"><\/script>\n?/g, '')
    .replace('<title>jobDo — Dashboard</title>',
      '<title>jobDo — Dashboard</title>\n<!-- Generated by scripts/sync-dashboard.mjs. Edit frontend/public/app/index.html. -->');
}

// [target file] -> generated contents
function planned() {
  const out = new Map();
  const app = path.join(root, 'frontend', 'public', 'app');
  const dash = path.join(root, 'extension', 'src', 'dashboard');
  for (const name of ['dashboard.css', 'dashboard.js', 'charts.js', 'source.js']) {
    const body = readFileSync(path.join(app, name), 'utf8');
    out.set(path.join(dash, name), name.endsWith('.js') ? banner('frontend/public/app') + body : body);
  }
  out.set(path.join(dash, 'dashboard.html'), extensionHtml(readFileSync(path.join(app, 'index.html'), 'utf8')));

  const shared = path.join(root, 'extension', 'src', 'shared');
  const web = path.join(root, 'frontend', 'public', 'shared');
  for (const name of ['defaults.js', 'sites.js', 'ats.js', 'resume.js']) {
    out.set(path.join(web, name), banner('extension/src/shared') + readFileSync(path.join(shared, name), 'utf8'));
  }
  return out;
}

const files = planned();
const rel = (p) => path.relative(root, p);

if (checkOnly) {
  const stale = [...files].filter(([target, body]) => !existsSync(target) || readFileSync(target, 'utf8') !== body);
  if (stale.length) {
    console.error('Out of date: ' + stale.map(([t]) => rel(t)).join(', '));
    console.error('Run: node scripts/sync-dashboard.mjs');
    process.exit(1);
  }
  console.log('Shared copies are in sync.');
} else {
  for (const [target, body] of files) {
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, body);
    console.log('  ' + rel(target));
  }
  console.log('\nWrote ' + files.size + ' files.');
}
